import { describe, it, expect } from 'vitest';
import {
  canSubmit,
  isProposedDateSubmittable,
  submissionProblems,
  PAST_PROPOSED_DATE_MESSAGE,
} from '@/domain/event-request/policy';
import {
  eventRequestCoreSchema,
  eventRequestDraftSchema,
} from '@/domain/event-request/schema';
import {
  formatSingaporeDate,
  formatSingaporeDateTime,
  isPastDate,
  todayInSingapore,
} from '@/domain/shared/dates';

/**
 * SCRUM-76 — Create an event request with basic details.
 *
 * AC text is taken from the Jira card, which is authoritative.
 *
 * Sheet mapping: US-5.1 = SCRUM-76+77+78, so its AC1-AC5 are written across all
 * three tickets (slots are 77, attendance is 78) and do not line up one-to-one
 * with SCRUM-76's own ACs. Only TC01 and TC05 touch this ticket; the date rule
 * and Singapore-time criteria have no row in the sheet yet and are tagged by
 * Jira AC until one exists.
 *
 * Submission itself is US-5.3 (SCRUM-82), not this ticket - SCRUM-76 owns only
 * the date RULE that submission applies, which is what is tested below.
 *
 * Not covered here, and not coverable by a unit test:
 *   AC1 (organisation pre-filled) — blocked on Authentication + Client
 *        Organisations. Verify manually once getCurrentActor() is implemented.
 *   AC2 (unique reference) — generated by a Postgres sequence, so it needs an
 *        integration test against a real database, not a unit test.
 */

const A_MONDAY = '2026-11-09';

/** A complete, submittable request. Individual tests vary one field at a time. */
function validRequest(proposedDate: string) {
  return {
    name: 'Annual Tech Summit',
    purpose: 'Networking',
    description: 'Yearly gathering',
    proposedDate: new Date(`${proposedDate}T00:00:00Z`),
    timeSlots: ['PM' as const],
    expectedAttendance: 80,
  };
}

describe('SCRUM-76 — Create an event request with basic details', () => {
  // US-5.1-TC01 (basic-details slice of the happy-path create test)
  it('accepts a complete request with all basic details', () => {
    expect(canSubmit(validRequest('2026-11-16'), A_MONDAY)).toBe(true);
  });

  describe('AC3 — a proposed date earlier than today blocks submission', () => {
    it('refuses a date that has already passed, and says why', () => {
      const problems = submissionProblems(validRequest('2026-11-08'), A_MONDAY);
      expect(problems).toContain(PAST_PROPOSED_DATE_MESSAGE);
    });

    it('still allows that same request to be saved as a draft', () => {
      // The draft schema is what a save is validated against, and it has no
      // opinion about dates at all - which is what keeps AC3's second half true.
      const result = eventRequestDraftSchema.safeParse(validRequest('2026-11-08'));
      expect(result.success).toBe(true);
    });

    it('allows a draft that is barely filled in at all', () => {
      expect(eventRequestDraftSchema.safeParse({ name: 'Just an idea' }).success).toBe(true);
      // ...but the same half-finished request is not submittable.
      expect(eventRequestCoreSchema.safeParse({ name: 'Just an idea' }).success).toBe(false);
    });
  });

  describe('AC4 — no minimum lead time applies', () => {
    it('accepts an event one week away', () => {
      expect(isProposedDateSubmittable(new Date('2026-11-16T00:00:00Z'), A_MONDAY)).toBe(true);
    });

    it('accepts an event today, the earliest date there is', () => {
      expect(isProposedDateSubmittable(new Date(`${A_MONDAY}T00:00:00Z`), A_MONDAY)).toBe(true);
    });

    it('accepts an event tomorrow — a short notice is not a rejection reason', () => {
      expect(isProposedDateSubmittable(new Date('2026-11-10T00:00:00Z'), A_MONDAY)).toBe(true);
    });
  });

  describe('AC5 — dates and times are shown in Singapore time', () => {
    // The bug this guards: at 18:00 UTC it is already the next day in Singapore
    // (UTC+8). Judging "today" on the server clock is wrong for 8 hours a day.
    it('treats 18:00 UTC as already the next calendar day in Singapore', () => {
      expect(todayInSingapore(new Date('2026-11-14T18:00:00Z'))).toBe('2026-11-15');
    });

    it('renders a timestamp on the Singapore side of midnight', () => {
      expect(formatSingaporeDateTime('2026-11-14T18:00:00Z')).toContain('15 Nov 2026');
    });

    it('renders a proposed date as the day that was chosen, not its UTC neighbour', () => {
      expect(formatSingaporeDate('2026-11-15')).toBe('15 Nov 2026');
    });

    it('a date is only past once Singapore has moved on', () => {
      expect(isPastDate('2026-11-14', '2026-11-15')).toBe(true);
      expect(isPastDate('2026-11-15', '2026-11-15')).toBe(false);
    });
  });

  // US-5.1-TC05 — missing mandatory field blocks save.
  // NOTE: the sheet says "blocks save"; Jira AC3 says saving a draft stays
  // allowed. Read here as blocking SUBMISSION, per Jira being authoritative.
  // Worth confirming with the team.
  it('blocks submission when a mandatory field is blank, naming the field', () => {
    const withoutPurpose = { ...validRequest('2026-11-16'), purpose: '' };
    expect(submissionProblems(withoutPurpose, A_MONDAY)).toContain('Purpose is required');
    expect(canSubmit(withoutPurpose, A_MONDAY)).toBe(false);
  });
});
