import { describe, it, expect } from 'vitest';
import { isProposedDateSubmittable } from '@/domain/event-request/policy';
import {
  eventRequestBasicDetailsSchema,
  eventRequestDraftSchema,
  eventRequestSaveSchema,
} from '@/domain/event-request/schema';
import {
  hasLongYear,
  isISODate,
  LATEST_DATE,
  formatSingaporeDate,
  formatSingaporeDateTime,
  isPastDate,
  todayInSingapore,
} from '@/domain/shared/dates';

/**
 * SCRUM-76 — Create an event request with basic details.
 *
 * AC text is taken from the Jira card, which is authoritative.
 *
 * Sheet mapping: US-5.1 = SCRUM-76+77+78, so its AC1-AC5 are written across all
 * three tickets and do not line up one-to-one with SCRUM-76's own ACs. TC01
 * (happy path) and TC05 (blank mandatory field) are this ticket's; TC02/TC03
 * are 77 and TC04 is 78. The date rule and Singapore-time criteria have no row
 * in the sheet yet and are tagged by Jira AC until one exists.
 *
 * Not covered here, and not coverable by a unit test:
 *   AC1 (organisation pre-filled) — blocked on the Client Organisations story;
 *        the form shows "Not yet linked to an organisation" until it lands.
 *        (Authentication is in, and getCurrentActor() reads the session.)
 *   AC2 (unique reference) — generated by a Postgres sequence; verify against
 *        a real database, not a unit test.
 *   Applying the date rule at submission is SCRUM-82 and is tested there.
 */

const A_MONDAY = '2026-11-09';

const basicDetails = {
  name: 'Annual Tech Summit',
  purpose: 'Networking',
  description: 'Yearly gathering',
  proposedDate: '2026-11-15',
};

describe('SCRUM-76 — Create an event request with basic details', () => {
  // US-5.1-TC01 (basic-details slice of the happy-path create test)
  it('accepts a request with name, purpose, description and proposed date', () => {
    expect(eventRequestBasicDetailsSchema.safeParse(basicDetails).success).toBe(true);
  });

  // US-5.1-TC05 — purpose left blank: request not created, "purpose" named
  it('refuses to save with a blank purpose, and names the missing field', () => {
    const result = eventRequestBasicDetailsSchema.safeParse({ ...basicDetails, purpose: '' });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.error.flatten().fieldErrors.purpose).toContain('Purpose is required');
    }
  });

  describe('AC3 — a proposed date earlier than today is not submittable, but is still savable', () => {
    it('judges a date that has already passed as not submittable', () => {
      expect(isProposedDateSubmittable(new Date('2026-11-08T00:00:00Z'), A_MONDAY)).toBe(false);
    });

    it('still allows that same request to be saved', () => {
      // The save schema checks the date is present and real, never whether it
      // has passed - which is what keeps AC3's second half true.
      const result = eventRequestBasicDetailsSchema.safeParse({
        ...basicDetails,
        proposedDate: '2026-11-08',
      });
      expect(result.success).toBe(true);
    });
  });

  describe('AC4 — no minimum lead time applies', () => {
    it('accepts an event one week away', () => {
      expect(isProposedDateSubmittable(new Date('2026-11-16T00:00:00Z'), A_MONDAY)).toBe(true);
    });

    it('accepts an event today, the earliest date there is', () => {
      expect(isProposedDateSubmittable(new Date(`${A_MONDAY}T00:00:00Z`), A_MONDAY)).toBe(true);
    });

    it('accepts an event tomorrow — short notice is not a rejection reason', () => {
      expect(isProposedDateSubmittable(new Date('2026-11-10T00:00:00Z'), A_MONDAY)).toBe(true);
    });
  });

  describe('AC5 — dates and times are shown in Singapore time', () => {
    // The bug this guards: at 18:00 UTC it is already the next day in Singapore
    // (UTC+8). Judging "today" on the server clock is wrong for 8 hours a day.
    it('treats 18:00 UTC as already the next calendar day in Singapore', () => {
      expect(todayInSingapore(new Date('2026-11-14T18:00:00Z'))).toBe('2026-11-15');
    });

    it('renders a timestamp on the Singapore side of midnight', () => {
      expect(formatSingaporeDateTime('2026-11-14T18:00:00Z')).toContain('15 Nov 2026');
    });

    it('renders a proposed date as the day that was chosen, not its UTC neighbour', () => {
      expect(formatSingaporeDate('2026-11-15')).toBe('15 Nov 2026');
    });

    it('a date is only past once Singapore has moved on', () => {
      expect(isPastDate('2026-11-14', '2026-11-15')).toBe(true);
      expect(isPastDate('2026-11-15', '2026-11-15')).toBe(false);
    });
  });
});

/**
 * TC-76-10 to TC-76-12 — the proposed date's year. The schema used
 * z.coerce.date(), which accepts a five-digit year such as 20266; the service
 * then wrote "+020266-12-10" and Postgres refused it with a raw error. The
 * date is now checked with the shared isISODate, like every other date field.
 */
describe('SCRUM-76 — the proposed date must be a real four-digit-year date', () => {
  const CHOOSE_A_VALID_DATE = 'Choose a valid date.';
  const saveWith = (proposedDate: unknown) => eventRequestSaveSchema.safeParse({ ...basicDetails, proposedDate });
  const draftWith = (proposedDate: unknown) =>
    eventRequestDraftSchema.safeParse({ name: basicDetails.name, proposedDate });

  // TC-76-10 (Happy path)
  it('accepts a four-digit-year date and keeps the day as typed', () => {
    const saved = saveWith('2026-12-10');
    expect(saved.success && saved.data.proposedDate.toISOString().slice(0, 10)).toBe('2026-12-10');
    const drafted = draftWith('2026-12-10');
    expect(drafted.success && drafted.data.proposedDate?.toISOString().slice(0, 10)).toBe('2026-12-10');
  });

  // TC-76-11 (Negative)
  it('refuses a five-digit year on the proposed date field, on save and on draft', () => {
    for (const result of [saveWith('20266-12-10'), draftWith('20266-12-10')]) {
      expect(result.success).toBe(false);
      if (!result.success) {
        expect(result.error.flatten().fieldErrors.proposedDate).toEqual([CHOOSE_A_VALID_DATE]);
      }
    }
  });

  // TC-76-12 (Boundary)
  it('accepts the last date with a four-digit year and refuses the first with five digits', () => {
    expect(saveWith('9999-12-31').success).toBe(true);
    const result = saveWith('10000-01-01');
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.error.flatten().fieldErrors.proposedDate).toEqual([CHOOSE_A_VALID_DATE]);
    }
  });

  it.each([
    ['a date that does not exist', '2026-02-30'],
    ['a six-digit year', '202666-12-10'],
    ['a signed year', '+020266-12-10'],
    ['a two-digit year', '26-12-10'],
    ['a date with a time', '2026-12-10T08:00:00Z'],
    ['text', 'next Tuesday'],
  ])('refuses %s', (_label, value) => {
    expect(saveWith(value).success).toBe(false);
    expect(draftWith(value).success).toBe(false);
  });

  it.each([
    ['a number', 20266],
    ['a Date object', new Date('2026-12-10T00:00:00Z')],
    ['null', null],
  ])('refuses %s on save, with the same message', (_label, value) => {
    const result = saveWith(value);
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.error.flatten().fieldErrors.proposedDate).toEqual([CHOOSE_A_VALID_DATE]);
    }
  });

  it('still lets a draft leave the date blank', () => {
    expect(draftWith('').success).toBe(true);
    expect(draftWith(undefined).success).toBe(true);
  });

  it('still names a missing date on save', () => {
    const { proposedDate: _omitted, ...withoutDate } = basicDetails;
    const result = eventRequestSaveSchema.safeParse(withoutDate);
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.error.flatten().fieldErrors.proposedDate).toEqual([CHOOSE_A_VALID_DATE]);
    }
  });
});

/**
 * The form keeps the Proposed date to a four-digit year (a browser date input
 * takes up to six); hasLongYear() is how it tells, and LATEST_DATE is its max.
 */
describe('SCRUM-76 — the form keeps the proposed date to a four-digit year', () => {
  it('sees a year of five or six digits as too long', () => {
    expect(hasLongYear('20266-12-10')).toBe(true);
    expect(hasLongYear('202666-12-10')).toBe(true);
    expect(hasLongYear('10000-01-01')).toBe(true);
  });

  it('lets a four-digit year, and an empty or part-typed value, through', () => {
    expect(hasLongYear('2026-12-10')).toBe(false);
    expect(hasLongYear('9999-12-31')).toBe(false);
    expect(hasLongYear('0006-02-20')).toBe(false);
    expect(hasLongYear('')).toBe(false);
  });

  it('has a latest date that is itself the last valid date', () => {
    expect(LATEST_DATE).toBe('9999-12-31');
    expect(isISODate(LATEST_DATE)).toBe(true);
    expect(hasLongYear(LATEST_DATE)).toBe(false);
  });
});
